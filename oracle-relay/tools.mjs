// Runs one model tool call. Never trusts the args. Returns what to tell the model,
// and what to tell the browser.
export function handleToolCall(lead, call) {
  const args = call?.args && typeof call.args === 'object' ? call.args : {};
  const err = (error) => ({ response: { ok: false, error }, events: [] });

  switch (call?.name) {
    case 'save_field': {
      const r = validateField(args.field, args.value);
      if (!r.ok) return err(r.error);
      lead.set(args.field, r.value);
      return { response: { ok: true }, events: [{ type: 'field', field: args.field, value: r.value }] };
    }
    case 'navigate': {
      if (typeof args.route !== 'string' || !Object.hasOwn(ROUTES, args.route)) {
        return err(`unknown route; valid routes: ${Object.keys(ROUTES).join(', ')}`);
      }
      if (args.product !== undefined && args.route !== 'product') return err('product only works with route product');
      const confirmsProduct = args.route === 'product' && AFFIRM_RE.test(lead.lastHeard);
      if (lead.intakeInProgress && !wantsNavigation(lead.lastHeard) && !confirmsProduct) {
        return err('Only navigate when the visitor asks to go somewhere. Continue the intake with your next question.');
      }
      let url = ROUTES[args.route];
      let demo;
      let product;
      if (args.route === 'product') {
        product = PRODUCT_CATALOGUE.find((p) => p.slug === args.product);
        if (!product) return err(`unknown product; valid products: ${PRODUCT_SLUGS.join(', ')}`);
        url = product.url;
      }
      if (args.demo !== undefined) {
        if (args.route !== 'demos') return err('demo only works with route demos');
        if (typeof args.demo !== 'string' || !DEMO_SLUGS.includes(args.demo)) return err(`unknown demo; valid demos: ${DEMO_SLUGS.join(', ')}`);
        url = demoUrl(args.demo);
        demo = args.demo;
      }
      return {
        response: { ok: true, note: 'The page is opening. Do not speak again; the visitor already heard your line.' },
        events: [{ type: 'navigate', route: args.route, url, ...(demo && { demo }), ...(product && { product: product.slug }) }],
      };
    }
    case 'finish_intake': {
      const picked = Array.isArray(args.next) ? [...new Set(args.next)] : [];
      if (!picked.length || !picked.every((n) => NEXT_STEPS.includes(n))) {
        return err('next must list one or more of plan, demo, call. Ask the visitor which they want: their automation plan, a live demo, or a call with the team.');
      }
      // Only one page can open. A call beats the planner; the planner beats demos (the planner cards link to them).
      const opensPlanner = picked.includes('plan') && !picked.includes('call');
      const lines = {
        plan: 'Say one short line, such as "Opening your automation plan." The page opens by itself; do NOT call navigate.',
        demo: 'Recommend the demo from the catalogue that best fits what they told you, name it, then call navigate with route demos and that demo slug. Say the one line before navigate and nothing after.',
        call: 'Say one short line, then call navigate with route book_meeting. Say nothing after the navigate response.',
      };
      const then = [opensPlanner ? lines.plan : picked.includes('call') ? lines.call : lines.demo];
      const navigate = opensPlanner
        ? [{ type: 'navigate', route: 'automation_plan', url: plannerUrl(args.industry_id, lead.snapshot().volume) }]
        : [];
      if (lead.completed) {
        // A later "also open the plan" just re-opens the planner; the lead is recorded once.
        if (!opensPlanner) return { response: { ok: true, alreadySubmitted: true }, events: [] };
        return { response: { ok: true, alreadySubmitted: true, then }, events: navigate };
      }
      const missing = lead.missing();
      if (missing.length) return { response: { ok: false, missing }, events: [] };
      lead.markCompleted();
      return {
        response: { ok: true, next: picked, then },
        events: [{ type: 'intake_complete', lead: lead.snapshot(), next: picked }, ...navigate],
      };
    }
    default:
      return err(`unknown tool: ${String(call?.name).slice(0, 40)}`);
  }
}

