#!/usr/bin/env python3
"""Split the Claude Enterprise Training Guide into lessons, quiz JSON, and browsers.

Source of truth is the single big guide markdown; everything under train/content/
is derived and regenerated by this script. Run after editing the guide:

    python3 scripts/build-training-content.py
    python3 scripts/build-training-content.py --check   # validate only, write nothing

Chunking follows the segmenting principle: modules are packed into lessons of
roughly TARGET_MINUTES, never splitting a section, so no lesson is a 34-minute
wall of text. Lesson titles are derived from real headings, never invented.
"""

import argparse
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
GUIDE = ROOT / "guide claude enterprise agent.final.md"
OUT = ROOT / "train" / "content"
LESSONS = OUT / "lessons"
HTML_DIR = ROOT / "train"

EXPECTED_MODULES = 23
EXPECTED_QUESTIONS = 100
LESSON_RANGE = (55, 80)          # sanity band for total lessons
WORDS_PER_MINUTE = 220
MIN_MINUTES = 2                  # fold runts shorter than this into the previous lesson
TARGET_MINUTES = 5               # pack sections up to here...
MAX_MINUTES = 9                  # ...and never exceed this in one lesson

# Modules that work better as a searchable tool than as linear reading.
