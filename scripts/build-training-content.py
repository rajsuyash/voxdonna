def clip(text: str, limit: int) -> str:
    """Trim to a word boundary and drop an unbalanced emphasis marker."""
    flat = re.sub(r"\s+", " ", text).strip()
    if len(flat) > limit:
        flat = flat[:limit].rsplit(" ", 1)[0].rstrip(" ,;:—-") + "…"
    if flat.count("**") % 2:
        flat = flat.replace("**", "", 1)
    if flat.count("`") % 2:
        flat = flat.replace("`", "", 1)
    return flat


def minutes(text: str) -> int:
    return max(1, round(len(text.split()) / WORDS_PER_MINUTE))


def clean_title(title: str) -> str:
    """Strip authoring numbering: '11.1 Installing' -> 'Installing'."""
    t = re.sub(r"^\d+(\.\d+)*\.?\s+", "", title.strip())
    t = re.sub(r"^(Chapter|Part)\s+\d+[:.]\s*", "", t, flags=re.I)
    return t.strip() or title.strip()


def strip_fences(lines):
    """Yield (index, line) for lines outside fenced code blocks."""
    in_fence = False
    for i, line in enumerate(lines):
        if line.startswith("```"):
            in_fence = not in_fence
            continue
        if not in_fence:
            yield i, line


# --------------------------------------------------------------------------
# module split
# --------------------------------------------------------------------------

def split_modules(text: str):
    lines = text.split("\n")
    starts = []
    for i, line in strip_fences(lines):
        m = re.match(r"^# (Part (\d+)|Appendix ([ABC])): (.+)$", line)
        if m:
            starts.append((i, m))

    modules = []
    for idx, (line_no, m) in enumerate(starts):
        end = starts[idx + 1][0] if idx + 1 < len(starts) else len(lines)
        body = "\n".join(lines[line_no:end]).strip() + "\n"
        if m.group(2):
            mid, kind, order = f"part-{int(m.group(2)):02d}", "part", int(m.group(2))
        else:
            mid, kind, order = f"appendix-{m.group(3).lower()}", "appendix", 100 + ord(m.group(3))
        modules.append({
            "id": mid, "kind": kind, "order": order,
            "label": m.group(1), "title": m.group(4).strip(), "body": body,
        })
    modules.sort(key=lambda x: x["order"])
    return modules


def split_sections(body: str):
    """Split a module body into (lede, [sections]) at ## / ### boundaries."""
    lines = body.split("\n")
    heads = []
    for i, line in strip_fences(lines):
        m = re.match(r"^(#{2,3}) (.+)$", line)
        if m:
            heads.append((i, len(m.group(1)), m.group(2).strip()))

    lede_end = heads[0][0] if heads else len(lines)
    lede = "\n".join(lines[1:lede_end]).strip()   # drop the module's own H1

    sections = []
    for idx, (line_no, level, title) in enumerate(heads):
        end = heads[idx + 1][0] if idx + 1 < len(heads) else len(lines)
        chunk_lines = lines[line_no:end]
        chunk = "\n".join(chunk_lines).rstrip()
        if minutes(chunk) > MAX_MINUTES:
            sections.extend(subsplit(chunk_lines, level, title))
        else:
            sections.append({"level": level, "title": title, "text": chunk,
                             "minutes": minutes(chunk)})
    return lede, sections


def subsplit(chunk_lines, level, title):
    """A section too long to be one lesson is split again at #### boundaries."""
    subs = [(i, l[5:].strip()) for i, l in strip_fences(chunk_lines)
            if l.startswith("#### ")]
    if not subs:
        text = "\n".join(chunk_lines).rstrip()
        return [{"level": level, "title": title, "text": text, "minutes": minutes(text)}]

    out = []
    head = "\n".join(chunk_lines[:subs[0][0]]).rstrip()
    for idx, (line_no, sub_title) in enumerate(subs):
        end = subs[idx + 1][0] if idx + 1 < len(subs) else len(chunk_lines)
        text = "\n".join(chunk_lines[line_no:end]).rstrip()
        if idx == 0 and head:
            text = head + "\n\n" + text          # keep the parent heading + intro
        out.append({"level": level, "title": title if idx == 0 else f"{title} — {sub_title}",
                    "text": text, "minutes": minutes(text)})
    return out


EXERCISE_RE = re.compile(r"^#### (Try it[^\n]*)\n+(.*?)(?=\n#{1,6} |\n---\s*$|\Z)", re.M | re.S)
CAVEAT_RE = re.compile(r"^(Caveat[:s].+)$", re.M)


def normalize_blocks(md: str):
    """Promote authored conventions into explicit ::: blocks the renderer knows.

    The guide already marks exercises and caveats; they were being rendered as
    ordinary headings and paragraphs. Converting here keeps the renderer generic
    and makes the transformation visible in the generated lesson files.
    """
    counts = {"exercise": 0, "caution": 0}

    def exercise(m):
        counts["exercise"] += 1
        return ":::exercise " + m.group(1).strip() + "\n" + m.group(2).strip() + "\n:::\n"

    def caution(m):
        counts["caution"] += 1
        return ":::caution\n" + m.group(1).strip() + "\n:::"

    md = EXERCISE_RE.sub(exercise, md)
    md = CAVEAT_RE.sub(caution, md)
    return md, counts


def pack_lessons(module, lede, sections):
    """Greedily pack sections into lessons of ~TARGET_MINUTES, never splitting one."""
    if not sections:
        return [{"index": 1, "title": clean_title(module["title"]),
                 "contains": [], "text": lede, "minutes": max(1, minutes(lede))}]

    groups, current, spent = [], [], 0
    for sec in sections:
        # An H2 always starts a fresh lesson; it marks a real authored boundary.
        hard_break = sec["level"] == 2 and current
        if current and (hard_break or spent + sec["minutes"] > MAX_MINUTES
                        or spent >= TARGET_MINUTES):
            groups.append(current)
            current, spent = [], 0
        current.append(sec)
        spent += sec["minutes"]
    if current:
        groups.append(current)

    # Greedy packing leaves a runt at the end (usually "Chapter summary").
    # Fold anything under MIN_MINUTES back into the lesson before it.
    merged = []
    for group in groups:
        spent = sum(s["minutes"] for s in group)
        if merged and spent < MIN_MINUTES and \
                sum(s["minutes"] for s in merged[-1]) + spent <= MAX_MINUTES:
            merged[-1].extend(group)
        else:
            merged.append(group)
    groups = merged

    lessons = []
    for i, group in enumerate(groups, 1):
        text = "\n\n".join(s["text"] for s in group)
        if i == 1 and lede:
            text = lede + "\n\n" + text
        lessons.append({
            "index": i,
            "title": clean_title(group[0]["title"]),
            "contains": [clean_title(s["title"]) for s in group[1:]],
            "text": text.strip() + "\n",
            "minutes": max(1, minutes(text)),
        })
    return lessons


