def parse_prompts(md: str):
    prompts, category = [], ""
    blocks = md.split("\n")
    i = 0
    while i < len(blocks):
        line = blocks[i].strip()
        cm = re.match(r"^### \d+\. (.+)$", line)
        if cm:
            category = cm.group(1).strip()
            i += 1
            continue
        pm = re.match(r"^\*\*(\d+)\. (.+?)\*\*$", line)
        if pm:
            body, pairs, j = [], "", i + 1
            while j < len(blocks) and not blocks[j].startswith("```"):
                j += 1
            if j < len(blocks):
                j += 1
                while j < len(blocks) and not blocks[j].startswith("```"):
                    body.append(blocks[j])
                    j += 1
                j += 1
            while j < len(blocks) and not blocks[j].strip():
                j += 1
            if j < len(blocks):
                pw = re.match(r"^\*Pairs with: (.+?)\.?\*$", blocks[j].strip())
                if pw:
                    pairs = pw.group(1).strip()
            prompts.append({"n": int(pm.group(1)), "title": pm.group(2).strip(),
                            "category": category, "body": "\n".join(body).strip(),
                            "pairs": pairs})
            i = j
            continue
        i += 1
    return prompts


def parse_mistakes(md: str):
    mistakes, category = [], ""
    for line in md.split("\n"):
        stripped = line.strip()
        cm = re.match(r"^### Category \d+: (.+?)(?: \(Mistakes .+?\))?$", stripped)
        if cm:
            category = cm.group(1).strip()
            continue
        mm = re.match(r"^\*\*Mistake (\d+): (.+?)\*\*\s*—\s*(.+)$", stripped)
        if mm:
            rest = mm.group(3).strip()
            body, fix = rest, ""
            fm = re.search(r"\bFix:\s*(.+)$", rest)
            if fm:
                body = rest[:fm.start()].strip().rstrip(".") + "."
                fix = fm.group(1).strip()
            mistakes.append({"n": int(mm.group(1)), "title": mm.group(2).strip(),
                             "category": category, "body": body, "fix": fix})
    return mistakes


def parse_glossary(md: str):
    terms, faq = [], []
    letter, in_faq, faq_category = "", False, ""
    lines = md.split("\n")
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("## ") and "Frequently Asked Questions" in stripped:
            in_faq = True
            continue
        lm = re.match(r"^### ([A-Z])$", stripped)
        if lm and not in_faq:
            letter = lm.group(1)
            continue
        cm = re.match(r"^### \d+\. (.+)$", stripped)
        if cm and in_faq:
            faq_category = cm.group(1).strip()
            continue
        if in_faq:
            qm = re.match(r"^\*\*Q\d+\. (.+?)\*\*$", stripped)
            if qm:
                answer = lines[i + 1].strip() if i + 1 < len(lines) else ""
                faq.append({"q": qm.group(1).strip(), "a": answer, "category": faq_category})
            continue
        tm = re.match(r"^\*\*(.+?)\*\*(?:\s*\((.+?)\))?\s*—\s*(.+)$", stripped)
        if tm and letter:
            terms.append({"term": tm.group(1).strip(), "status": (tm.group(2) or "").strip(),
                          "def": tm.group(3).strip(), "letter": letter})
    return {"terms": terms, "faq": faq}


def parse_sheets(md: str):
    sheets = []
    lines = md.split("\n")
    heads = [(i, l) for i, l in strip_fences(lines) if l.startswith("### ")]
    for idx, (line_no, head) in enumerate(heads):
        end = heads[idx + 1][0] if idx + 1 < len(heads) else len(lines)
        title = head[4:].strip()
        sm = re.match(r"^Sheet (\d+) — (.+)$", title)
        sheets.append({
            "n": int(sm.group(1)) if sm else 90 + idx,
            "title": sm.group(2).strip() if sm else title,
            "body": "\n".join(lines[line_no + 1:end]).strip(),
        })
    return sheets


# --------------------------------------------------------------------------

def git_stamp() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                              cwd=ROOT, capture_output=True, text=True,
                              check=True).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "dev"


def bust_cache(stamp: str) -> int:
    pattern = re.compile(r'((?:href|src)="(?:\./)?[\w./-]+\.(?:css|js))\?v=[\w.]+"')
    touched = 0
    for html in sorted(HTML_DIR.glob("*.html")):
        original = html.read_text(encoding="utf-8")
        updated = pattern.sub(rf'\1?v={stamp}"', original)
        if updated != original:
            html.write_text(updated, encoding="utf-8")
            touched += 1
    return touched


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="validate only, write nothing")
    args = ap.parse_args()

    if not GUIDE.exists():
        sys.exit(f"guide not found: {GUIDE}")
    text = GUIDE.read_text(encoding="utf-8")

    modules = split_modules(text)
    if len(modules) != EXPECTED_MODULES:
        sys.exit(f"split {len(modules)} modules, expected {EXPECTED_MODULES}")

    by_id = {m["id"]: m for m in modules}
    questions, quiz_sections = parse_quiz(by_id["appendix-b"]["body"])
    by_id["appendix-b"]["body"] = strip_answer_key(by_id["appendix-b"]["body"])

    browsers = {
        "prompts": parse_prompts(by_id["part-20"]["body"]),
        "mistakes": parse_mistakes(by_id["part-17"]["body"]),
        "glossary": parse_glossary(by_id["appendix-a"]["body"]),
        "sheets": parse_sheets(by_id["appendix-c"]["body"]),
    }

    problems = []
    if len(browsers["prompts"]) < 100:
        problems.append(f"prompt library: parsed {len(browsers['prompts'])}, expected >= 100")
    if any(not p["body"] for p in browsers["prompts"]):
        problems.append("prompt library: some prompts have an empty body")
    if len(browsers["mistakes"]) != 100:
        problems.append(f"pitfalls: parsed {len(browsers['mistakes'])}, expected 100")
    if any(not m["fix"] for m in browsers["mistakes"]):
        problems.append("pitfalls: some mistakes have no Fix")
    if len(browsers["glossary"]["terms"]) < 40:
        problems.append(f"glossary: only {len(browsers['glossary']['terms'])} terms")
    if len(browsers["glossary"]["faq"]) < 20:
        problems.append(f"glossary: only {len(browsers['glossary']['faq'])} FAQ entries")
    if len(browsers["sheets"]) < 8:
        problems.append(f"cheat sheets: only {len(browsers['sheets'])}")
    if problems:
        sys.exit("browser parse failed:\n  - " + "\n  - ".join(problems))

    # ---- lessons ----
    manifest_modules, lesson_files, total_lessons = [], {}, 0
    block_counts = {"exercise": 0, "caution": 0}
    for m in modules:
        view = BROWSER_MODULES.get(m["id"])
        lede, sections = split_sections(m["body"])
        module_minutes = minutes(m["body"])

        if view:
            lessons = [{"index": 1, "title": m["title"], "contains": [],
                        "text": m["body"], "minutes": module_minutes}]
        else:
            lessons = pack_lessons(m, lede, sections)

        entries = []
        for lesson in lessons:
            lesson["text"], counts = normalize_blocks(lesson["text"])
            for k, v in counts.items():
                block_counts[k] += v
            lid = m["id"] if view else f"{m['id']}-l{lesson['index']}"
            fname = f"{lid}.md"
            lesson_files[fname] = lesson["text"]
            entries.append({
                "id": lid, "title": lesson["title"], "contains": lesson["contains"],
                "file": f"lessons/{fname}", "minutes": lesson["minutes"], "questions": [],
            })
            total_lessons += 1

        section_no = next((s for s, mid in SECTION_TO_MODULE.items() if mid == m["id"]), None)
        if section_no:
            mine = [q["n"] for q in questions if q["section"] == section_no]
            for pos, qn in enumerate(mine):
                entries[pos % len(entries)]["questions"].append(qn)

        first_para = clip(next((p.strip() for p in lede.split("\n\n") if p.strip()), ""), 320)
        manifest_modules.append({
            "id": m["id"], "label": m["label"], "title": m["title"], "kind": m["kind"],
            "minutes": module_minutes, "quizSection": section_no, "view": view,
            "lede": first_para,
            "lessons": entries,
        })

    if block_counts["exercise"] < 25:
        sys.exit(f"only {block_counts['exercise']} 'Try it' exercises promoted, expected ~33")
    if not LESSON_RANGE[0] <= total_lessons <= LESSON_RANGE[1]:
        sys.exit(f"packed {total_lessons} lessons, expected {LESSON_RANGE[0]}-{LESSON_RANGE[1]}")
    for mod in manifest_modules:
        for lesson in mod["lessons"]:
            if not lesson_files[pathlib.Path(lesson["file"]).name].strip():
                sys.exit(f"{lesson['id']}: empty lesson body")
            if not mod["view"] and lesson["minutes"] > MAX_MINUTES:
                sys.exit(f"{lesson['id']}: {lesson['minutes']} min exceeds the cap")

    module_ids = [m["id"] for m in manifest_modules]
    for path in PATHS.values():
        if path["modules"] is None:
            path["modules"] = list(module_ids)
        unknown = [m for m in path["modules"] if m not in module_ids]
        if unknown:
            sys.exit(f"learning path references unknown modules: {unknown}")

    stamp = git_stamp()
    manifest = {
        "version": stamp, "source": GUIDE.name,
        "modules": manifest_modules, "paths": PATHS,
        "exam": {"total": EXPECTED_QUESTIONS, "passMark": 80, "sectionFloor": 6},
        "review": {"intervalDays": [1, 3, 7, 21]},
        "counts": {
            "lessons": total_lessons,
            "prompts": len(browsers["prompts"]),
            "mistakes": len(browsers["mistakes"]),
            "terms": len(browsers["glossary"]["terms"]),
            "faq": len(browsers["glossary"]["faq"]),
            "sheets": len(browsers["sheets"]),
            "exercises": block_counts["exercise"],
            "caveats": block_counts["caution"],
        },
    }

    if args.check:
        print(f"ok — {len(modules)} modules, {total_lessons} lessons, "
              f"{len(questions)} questions, {len(browsers['prompts'])} prompts, "
              f"{len(browsers['mistakes'])} pitfalls, "
              f"{len(browsers['glossary']['terms'])} terms, "
              f"{len(browsers['sheets'])} sheets, "
              f"{block_counts['exercise']} exercises, version {stamp}")
        return

    OUT.mkdir(parents=True, exist_ok=True)
    LESSONS.mkdir(parents=True, exist_ok=True)
    for stale in list(OUT.glob("*.md")) + list(LESSONS.glob("*.md")):
        stale.unlink()
    for name, body in lesson_files.items():
        (LESSONS / name).write_text(body, encoding="utf-8")

    def dump(name, payload):
        (OUT / name).write_text(
            json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    dump("manifest.json", manifest)
    dump("quiz.json", {"version": stamp, "sections": quiz_sections, "questions": questions})
    dump("prompts.json", {"version": stamp, "prompts": browsers["prompts"]})
    dump("mistakes.json", {"version": stamp, "mistakes": browsers["mistakes"]})
