QUESTION_RE = re.compile(r"^\*\*Q(\d+)\.\*\*\s*(.+)$")
OPTION_RE = re.compile(r"^([ABCD])\)\s*(.+)$")
SECTION_RE = re.compile(r"^### Section (\d+) — (.+)$")
ANSWER_RE = re.compile(r"^(\d+)\.\s+\*\*([ABCD])\*\*\s*—\s*(.+)$")


def parse_quiz(appendix_b: str):
    head, _, key_block = appendix_b.partition("### Answer Key")
    if not key_block:
        sys.exit("Appendix B: '### Answer Key' heading not found")

    answers = {}
    for line in key_block.split("\n"):
        m = ANSWER_RE.match(line.strip())
        if m:
            answers[int(m.group(1))] = {"correct": m.group(2), "why": m.group(3).strip()}

    questions, current = [], None
    section_no, section_title = 0, ""
    for line in head.split("\n"):
        stripped = line.strip()
        sm = SECTION_RE.match(stripped)
        if sm:
            section_no, section_title = int(sm.group(1)), sm.group(2).strip()
            continue
        qm = QUESTION_RE.match(stripped)
        if qm:
            current = {"n": int(qm.group(1)), "section": section_no,
                       "sectionTitle": section_title, "q": qm.group(2).strip(),
                       "options": {}}
            questions.append(current)
            continue
        om = OPTION_RE.match(stripped)
        if om and current is not None and om.group(1) not in current["options"]:
            current["options"][om.group(1)] = om.group(2).strip()

    problems = []
    if len(questions) != EXPECTED_QUESTIONS:
        problems.append(f"parsed {len(questions)} questions, expected {EXPECTED_QUESTIONS}")
    if len(answers) != EXPECTED_QUESTIONS:
        problems.append(f"parsed {len(answers)} answers, expected {EXPECTED_QUESTIONS}")

    for q in questions:
        missing = [k for k in "ABCD" if k not in q["options"]]
        if missing:
            problems.append(f"Q{q['n']}: missing options {missing}")
        a = answers.get(q["n"])
        if not a:
            problems.append(f"Q{q['n']}: no answer key entry")
            continue
        q["correct"], q["why"] = a["correct"], a["why"]
        q["options"] = [{"key": k, "text": q["options"].get(k, "")} for k in "ABCD"]

    if sorted(q["n"] for q in questions) != list(range(1, EXPECTED_QUESTIONS + 1)):
        problems.append("question numbering is not a contiguous 1..100 run")
    if problems:
        sys.exit("quiz parse failed:\n  - " + "\n  - ".join(problems))

    sections = {}
    for q in questions:
        sections.setdefault(q["section"],
                            {"n": q["section"], "title": q["sectionTitle"], "count": 0})["count"] += 1
    return questions, [sections[k] for k in sorted(sections)]


def strip_answer_key(appendix_b: str) -> str:
    head, _, _ = appendix_b.partition("### Answer Key")
    return head.rstrip() + (
        "\n\n---\n\n> The answer key lives in the exam, not on this page. "
        "Sit the certification exam to see your score, the correct answers, "
        "and the reasoning behind each one.\n"
    )


